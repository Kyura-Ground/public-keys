set -eo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

shopt -s nullglob
platform_keys=(../../../build/make/target/product/security/*.pk8)
if [[ ${#platform_keys[@]} -eq 0 || ! -f ../../../external/avb/avbtool.py ]]; then
    echo "Run from vendor/lineage-priv/keys in a complete Android source tree." >&2
    exit 1
fi
mapfile -t override_keys < <(grep -o ':.*override' keys.mk | sort -u)

# Generate the certificate modules used by PRODUCT_CERTIFICATE_OVERRIDES.
echo "// DO NOT EDIT THIS FILE MANUALLY" > Android.bp
for key in "${override_keys[@]}"; do
    key=${key#:}
    cat >> Android.bp <<EOF_MODULE

android_app_certificate {
    name: "$key",
    certificate: "$key",
}
EOF_MODULE
done

./make_key.sh avb 4096
python3 ../../../external/avb/avbtool.py extract_public_key --key avb.pk8 --output avb_custom_key.bin
./make_key.sh releasekey 4096
for key in "${platform_keys[@]}"; do
    ./make_key.sh "$(basename "$key" .pk8)"
done
for key in "${override_keys[@]}"; do
    ./make_key.sh "${key#:}" 4096
done
